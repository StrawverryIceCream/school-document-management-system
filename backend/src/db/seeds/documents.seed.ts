export async function seedDocuments() {
  console.log("🌱 Seeding 51 TUP Manila Official Documents...");

  // Fetch all offices to resolve officeId by code
  const allOffices = await db.query.offices.findMany({
    columns: { id: true, code: true },
  });
  const officeMap = new Map(allOffices.map((o) => [o.code, o.id]));

  let count = 0;
  for (const doc of RAW_DOCUMENTS) {
    const officeId = officeMap.get(doc.officeCode);
    if (!officeId) {
      console.warn(`⚠️ Warning: Office with code "${doc.officeCode}" not found for doc ${doc.code}. Skipping.`);
      continue;
    }

    const legacyOffice = doc.officeCode === "HRMO" ? "hr" : "registrar";
    const legacyCategory = doc.allowedCategories.includes("student")
      ? "student"
      : doc.allowedCategories.includes("teacher")
      ? "teacher"
      : "staff";

    await db
      .insert(documentTypes)
      .values({
        code: doc.code,
        name: doc.name,
        officeId,
        office: legacyOffice,
        category: legacyCategory,
        allowedCategories: doc.allowedCategories,
        allowedStudentStatuses: doc.allowedStudentStatuses || [],
        description: doc.description,
        instructions: doc.instructions,
        fee: doc.fee,
        feeUnit: doc.feeUnit,
        processingDays: doc.processingDays,
        slaMinutes: doc.slaMinutes,
        routingTemplate: doc.routingTemplate || [],
        isActive: true,
      })
      .onConflictDoUpdate({
        target: documentTypes.code,
        set: {
          name: doc.name,
          officeId,
          allowedCategories: doc.allowedCategories,
          allowedStudentStatuses: doc.allowedStudentStatuses || [],
          description: doc.description,
          instructions: doc.instructions,
          fee: doc.fee,
          feeUnit: doc.feeUnit,
          processingDays: doc.processingDays,
          slaMinutes: doc.slaMinutes,
          routingTemplate: doc.routingTemplate || [],
          isActive: true,
        },
      });

    count++;
  }

  console.log(`✅ Successfully seeded ${count} TUP Manila document types!`);
}

// Self-run when executed directly
if (process.argv[1]?.endsWith("documents.seed.ts")) {
  seedDocuments()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error("❌ Document seed failed:", err);
      process.exit(1);
    });
}
