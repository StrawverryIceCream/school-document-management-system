import {
  Check,
  ClipboardCheck,
  Landmark,
  QrCode,
} from "lucide-react";
import type { FormDataValue } from "@/api/requests";
import { Card } from "@/components/ui/card";
import { TONES } from "@/lib/tones";
import { cn } from "@/lib/utils";

interface PaymentRequestSummaryProps {
  documentName: string;
  feeLabel: string;
  formData: Record<string, FormDataValue>;
  paymentRequired: boolean;
}

function getPurpose(formData: Record<string, FormDataValue>): string {
  const purpose = Object.entries(formData).find(([label, value]) =>
    label.toLowerCase().includes("purpose") &&
    typeof value === "string" &&
    value.trim().length > 0,
  );
  return purpose ? String(purpose[1]) : "Provided with request details";
}

function PaymentRequestSummary({
  documentName,
  feeLabel,
  formData,
  paymentRequired,
}: PaymentRequestSummaryProps) {
  const details = [
    ["Requested item", documentName],
    ["Intended purpose", getPurpose(formData)],
    ["Filing timestamp", "Created after submission"],
    ["Target release", "Set by Registrar"],
    ["Assigned counter", "To be assigned"],
  ];

  return (
    <Card className="overflow-hidden rounded-xl border-0 p-0 shadow-md">
      <div className="bg-primary px-4 py-4 text-primary-foreground sm:px-5">
        <div className="flex items-center justify-between gap-3">
          <div className="flex items-center gap-2.5">
            <span className="flex size-8 items-center justify-center rounded-md bg-white/15">
              <Landmark className="size-4" aria-hidden="true" />
            </span>
            <div>
              <p className="text-sm font-medium uppercase tracking-[0.15em] text-primary-foreground/80">
                Request Summary
              </p>
              <h2 className="text-base font-bold">Request Preview</h2>
            </div>
          </div>
          <span className="rounded bg-primary-foreground/15 px-2 py-1 text-sm font-bold tracking-wide">
            PREVIEW
          </span>
        </div>
        <p className="mt-3 text-sm leading-relaxed text-primary-foreground/80">
          An official claim slip is not generated by this step.
        </p>
      </div>

      <div className="space-y-3 p-3 sm:p-4">
        <div className="rounded-lg bg-muted px-3 py-2.5">
          <p className="text-sm font-semibold uppercase tracking-wide text-muted-foreground">
            Reference tracking no.
          </p>
          <p className="mt-1 font-mono text-sm font-semibold text-primary">
            Assigned after submission
          </p>
        </div>

        <div className="flex flex-col items-center rounded-lg border bg-card px-3 py-4 text-center">
          <div className="flex size-32 items-center justify-center rounded-lg bg-white text-primary shadow-sm">
            <QrCode className="size-20" strokeWidth={1.6} aria-hidden="true" />
          </div>
          <p className="mt-2 max-w-52 text-sm leading-relaxed text-muted-foreground">
            QR codes are not generated in this preview.
          </p>
        </div>

        <dl className="space-y-2 border-b pb-3">
          {details.map(([label, value]) => (
            <div
              key={label}
              className="flex items-start justify-between gap-3 text-sm"
            >
              <dt className="shrink-0 text-muted-foreground">{label}</dt>
              <dd className="max-w-[62%] text-right font-medium">{value}</dd>
            </div>
          ))}
        </dl>

        <div className="rounded-lg bg-muted p-3">
          <p className="mb-2 text-center text-sm font-semibold uppercase tracking-wide text-muted-foreground">
            Claim requirements
          </p>
          <ul className="space-y-2">
            {[
              "Keep your valid student or government-issued ID ready.",
              paymentRequired
                ? "Upload an official payment receipt for verification."
                : "No payment receipt is required for this request.",
              "Follow the Registrar's instructions when collecting your document.",
            ].map((requirement) => (
              <li
                key={requirement}
                className="flex items-start gap-2 text-sm leading-relaxed text-muted-foreground"
              >
                <span className="mt-0.5 flex size-4 shrink-0 items-center justify-center rounded-[2px] border border-primary text-primary">
                  <Check className="size-3" aria-hidden="true" />
                </span>
                {requirement}
              </li>
            ))}
          </ul>
        </div>

        <div className="flex items-center justify-between gap-2 rounded-md bg-muted/70 px-3 py-2 text-sm text-muted-foreground">
          <span className="inline-flex items-center gap-1.5">
            <ClipboardCheck
              className={cn("size-4", TONES.brand.value)}
              aria-hidden="true"
            />
            {paymentRequired
              ? "Payment proof reviewed by staff"
              : "No payment required"}
          </span>
          <span className="font-mono">DRAFT</span>
        </div>
        <div className="flex items-center justify-between gap-2 border-t pt-2 text-sm">
          <span className="text-muted-foreground">
            {paymentRequired ? "Settlement due" : "Payment status"}
          </span>
          <span className="text-right font-bold text-primary">
            {paymentRequired ? feeLabel : "No payment required"}
          </span>
        </div>
      </div>
    </Card>
  );
}

export default PaymentRequestSummary;
